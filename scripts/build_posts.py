#!/usr/bin/env python3
"""
Turns the Markdown files in content/posts/ into blog pages. Standard library only.

To publish a writeup, add content/posts/my-title.md starting with:

    ---
    title: My title
    date: 2026-11-15
    summary: One or two sentences shown in lists and search results.
    tags: Ransomware, Guide
    ---

then write the article below it. Supported Markdown: ## and ### headings, paragraphs,
bullet and numbered lists, > quotes, ``` code blocks, simple | tables |, **bold**,
*italic*, `code` and [links](https://example.com). Raw HTML is shown as text, not run.

Writes blog/<slug>/index.html, data/posts.json and sitemap.xml.
Run from the repository root:  python scripts/build_posts.py
"""
from __future__ import annotations

import html
import json
import os
import re
import shutil
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
POSTS_DIR = os.path.join(ROOT, "content", "posts")
BLOG_DIR = os.path.join(ROOT, "blog")
SITE = "https://www.threatintelspecialist.com"
MARKER = "<!-- generated by scripts/build_posts.py; edit the Markdown in content/posts instead -->"

CSP = ("default-src 'self'; script-src 'self' https://www.googletagmanager.com; "
       "style-src 'self' https://fonts.googleapis.com; font-src https://fonts.gstatic.com; "
       "img-src 'self' data: https://www.google-analytics.com https://www.googletagmanager.com; "
       "connect-src 'self' https://www.google-analytics.com https://*.google-analytics.com https://www.googletagmanager.com; "
       "base-uri 'self'; form-action 'self'; object-src 'none'")
FONTS = ("https://fonts.googleapis.com/css2?family=Atkinson+Hyperlegible+Next:wght@400;500;700"
         "&family=Bricolage+Grotesque:opsz,wght@12..96,500..800&display=swap")


def page(title: str, description: str, page_id: str, body: str, scripts: tuple[str, ...] = (), path: str = "/", marker: str = "") -> str:
    """The shell every page on the site shares."""
    e = html.escape
    tags = "".join(f'\n<script src="/assets/{s}"></script>' for s in ("site.js",) + tuple(scripts))
    return f"""<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>{e(title)}</title>
<meta name="description" content="{e(description)}">
<meta http-equiv="Content-Security-Policy" content="{CSP}">
<meta name="referrer" content="strict-origin-when-cross-origin">
<link rel="canonical" href="{SITE}{e(path)}">
<meta property="og:title" content="{e(title)}">
<meta property="og:description" content="{e(description)}">
<meta property="og:type" content="website">
<meta property="og:url" content="{SITE}{e(path)}">
<link rel="icon" href="/images/mark.svg" type="image/svg+xml">
<link rel="preconnect" href="https://fonts.googleapis.com">
<link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
<link rel="stylesheet" href="{FONTS}">
<link rel="stylesheet" href="/assets/site.css">
<script src="/assets/theme.js"></script>
</head>
<body data-page="{e(page_id)}">{marker}
<a class="skip" href="#main">Skip to content</a>
<header id="site-header"></header>
<main id="main">
{body.strip()}
</main>
<footer id="site-footer"></footer>
<noscript><p class="wrap">This site needs JavaScript to load its live data and menu.</p></noscript>{tags}
</body>
</html>
"""


# ───────────────────────── Markdown ─────────────────────────

def inline(text: str) -> str:
    text = html.escape(text, quote=True)
    codes: list[str] = []

    def stash(m):
        codes.append(m.group(1))
        return f"\x00{len(codes) - 1}\x00"

    text = re.sub(r"`([^`]+)`", stash, text)

    def link(m):
        label, url = m.group(1), html.unescape(m.group(2)).strip()
        if not re.match(r"^(https?://|/)[^\s\"'<>]*$", url):
            return m.group(0)
        external = url.startswith("http")
        extra = ' rel="noopener noreferrer" target="_blank"' if external else ""
        return f'<a href="{html.escape(url, quote=True)}"{extra}>{label}</a>'

    text = re.sub(r"\[([^\]]+)\]\(([^)\s]+)\)", link, text)
    text = re.sub(r"\*\*([^*]+)\*\*", r"<strong>\1</strong>", text)
    text = re.sub(r"(?<![*\w])\*([^*\s][^*]*)\*(?!\w)", r"<em>\1</em>", text)
    return re.sub(r"\x00(\d+)\x00", lambda m: f"<code>{codes[int(m.group(1))]}</code>", text)


def markdown(src: str) -> str:
    lines = src.replace("\r\n", "\n").split("\n")
    out: list[str] = []
    i = 0
    while i < len(lines):
        line = lines[i]
        if not line.strip():
            i += 1
        elif line.startswith("```"):
            i += 1
            code = []
            while i < len(lines) and not lines[i].startswith("```"):
                code.append(lines[i])
                i += 1
            i += 1
            out.append("<pre><code>" + html.escape("\n".join(code)) + "</code></pre>")
        elif m := re.match(r"^(#{2,3})\s+(.*)$", line):
            level = len(m.group(1))
            out.append(f"<h{level}>{inline(m.group(2).strip())}</h{level}>")
            i += 1
        elif line.startswith(">"):
            quote = []
            while i < len(lines) and lines[i].startswith(">"):
                quote.append(lines[i][1:].strip())
                i += 1
            out.append("<blockquote><p>" + inline(" ".join(quote)) + "</p></blockquote>")
        elif re.match(r"^\s*([-*]|\d+\.)\s+", line):
            ordered = bool(re.match(r"^\s*\d+\.", line))
            items = []
            while i < len(lines) and (re.match(r"^\s*([-*]|\d+\.)\s+", lines[i]) or (lines[i].startswith("  ") and lines[i].strip() and items)):
                if m := re.match(r"^\s*(?:[-*]|\d+\.)\s+(.*)$", lines[i]):
                    items.append(m.group(1))
                else:
                    items[-1] += " " + lines[i].strip()
                i += 1
            tag = "ol" if ordered else "ul"
            out.append(f"<{tag}>" + "".join(f"<li>{inline(it)}</li>" for it in items) + f"</{tag}>")
        elif line.lstrip().startswith("|") and i + 1 < len(lines) and re.match(r"^\s*\|[\s:|-]+\|\s*$", lines[i + 1]):
            def cells(row):
                return [c.strip() for c in row.strip().strip("|").split("|")]
            head = cells(line)
            i += 2
            rows = []
            while i < len(lines) and lines[i].lstrip().startswith("|"):
                rows.append(cells(lines[i]))
                i += 1
            out.append("<table><thead><tr>" + "".join(f"<th>{inline(c)}</th>" for c in head) + "</tr></thead><tbody>"
                       + "".join("<tr>" + "".join(f"<td>{inline(c)}</td>" for c in r) + "</tr>" for r in rows)
                       + "</tbody></table>")
        else:
            para = []
            while i < len(lines) and lines[i].strip() and not re.match(r"^(#{2,3}\s|>|```|\s*([-*]|\d+\.)\s+)", lines[i]):
                para.append(lines[i].strip())
                i += 1
            out.append("<p>" + inline(" ".join(para)) + "</p>")
    return "\n".join(out)


def read_post(path: str) -> dict | None:
    with open(path, encoding="utf-8") as fh:
        raw = fh.read()
    m = re.match(r"^---\s*\n(.*?)\n---\s*\n(.*)$", raw, re.S)
    if not m:
        print(f"  ! {os.path.basename(path)}: missing the --- header block, skipped", file=sys.stderr)
        return None
    meta = {}
    for line in m.group(1).splitlines():
        if ":" in line:
            key, value = line.split(":", 1)
            meta[key.strip().lower()] = value.strip()
    if not meta.get("title") or not re.match(r"^\d{4}-\d{2}-\d{2}$", meta.get("date", "")):
        print(f"  ! {os.path.basename(path)}: needs a title and a date like 2026-11-15, skipped", file=sys.stderr)
        return None
    if meta.get("draft", "").lower() in ("true", "yes"):
        return None
    slug = re.sub(r"[^a-z0-9]+", "-", os.path.splitext(os.path.basename(path))[0].lower()).strip("-")
    body = m.group(2)
    return {
        "slug": slug,
        "url": f"/blog/{slug}/",
        "title": meta["title"],
        "date": meta["date"],
        "summary": meta.get("summary", ""),
        "tags": [t.strip() for t in meta.get("tags", "").split(",") if t.strip()],
        "author": meta.get("author", "Threat Intel Specialist"),
        "minutes": max(1, round(len(body.split()) / 220)),
        "body": body,
    }


def human_date(date: str) -> str:
    months = "January February March April May June July August September October November December".split()
    y, m, d = date.split("-")
    return f"{int(d)} {months[int(m) - 1]} {y}"


def main() -> int:
    posts = []
    if os.path.isdir(POSTS_DIR):
        for name in sorted(os.listdir(POSTS_DIR)):
            if name.endswith(".md"):
                post = read_post(os.path.join(POSTS_DIR, name))
                if post:
                    posts.append(post)
    posts.sort(key=lambda p: (p["date"], p["slug"]), reverse=True)

    # remove pages for posts that no longer exist (only ones this script created)
    keep = {p["slug"] for p in posts}
    for name in os.listdir(BLOG_DIR):
        index = os.path.join(BLOG_DIR, name, "index.html")
        if name not in keep and os.path.isfile(index):
            with open(index, encoding="utf-8") as fh:
                if MARKER in fh.read():
                    shutil.rmtree(os.path.join(BLOG_DIR, name))

    e = html.escape
    for p in posts:
        body = f"""
<article class="wrap">
  <header class="page-head">
    <h1>{e(p['title'])}</h1>
    <p class="post-meta">{e(p['author'])}, {human_date(p['date'])}. {p['minutes']} min read.</p>
  </header>
  <div class="prose">
{markdown(p['body'])}
    <p><a href="/blog/">All writeups</a></p>
  </div>
</article>"""
        out_dir = os.path.join(BLOG_DIR, p["slug"])
        os.makedirs(out_dir, exist_ok=True)
        with open(os.path.join(out_dir, "index.html"), "w", encoding="utf-8") as fh:
            fh.write(page(f"{p['title']} — Threat Intel Specialist", p["summary"], "blog", body, path=p["url"], marker="\n" + MARKER))

    index = [{k: p[k] for k in ("slug", "url", "title", "date", "summary", "tags", "author", "minutes")} for p in posts]
    os.makedirs(os.path.join(ROOT, "data"), exist_ok=True)
    with open(os.path.join(ROOT, "data", "posts.json"), "w", encoding="utf-8") as fh:
        json.dump({"posts": index}, fh, ensure_ascii=False, indent=1)
        fh.write("\n")

    urls = ["/", "/news/", "/vulnerabilities/", "/incidents/", "/incidents/history/", "/blog/", "/learn/", "/about/"] + [p["url"] for p in posts]
    with open(os.path.join(ROOT, "sitemap.xml"), "w", encoding="utf-8") as fh:
        fh.write('<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n')
        fh.write("".join(f"  <url><loc>{SITE}{u}</loc></url>\n" for u in urls))
        fh.write("</urlset>\n")

    print(f"Built {len(posts)} posts.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
